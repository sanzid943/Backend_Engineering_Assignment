"""
Given a tuple of numbers, print its maximum and minimum (hint: max() and min() work on tuples too).

"""

input_touple= (34, 23, 57, 78, 35, 89, 44)

maximum= max(input_touple)
minimum= min(input_touple)

print("Touple: ", input_touple)
print("Maximum value: ", maximum)
print("Minimum value: ", minimum)

